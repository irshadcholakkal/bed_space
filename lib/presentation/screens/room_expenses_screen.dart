import 'package:flutter/cupertino.dart';
import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:intl/intl.dart';

import '../../../data/models/expense_model.dart';
import '../../../data/models/room_model.dart';
import '../../../presentation/blocs/management/management_bloc.dart';
import '../../../presentation/theme/app_theme.dart';

class RoomExpensesScreen extends StatefulWidget {
  final RoomModel room;

  const RoomExpensesScreen({super.key, required this.room});

  @override
  State<RoomExpensesScreen> createState() => _RoomExpensesScreenState();
}

class _RoomExpensesScreenState extends State<RoomExpensesScreen> {
  final _formKey = GlobalKey<FormState>();
  final _amountController = TextEditingController();
  final _descriptionController = TextEditingController();
  ExpenseType _selectedType = ExpenseType.maintenance;
  DateTime _selectedDate = DateTime.now();

  @override
  void dispose() {
    _amountController.dispose();
    _descriptionController.dispose();
    super.dispose();
  }

  void _submitExpense() {
    if (_formKey.currentState!.validate()) {
      final amount = double.parse(_amountController.text);
      final expense = ExpenseModel(
        id: '', // Generated by repo
        roomId: widget.room.roomId!,
        expenseType: _selectedType,
        amount: amount,
        date: _selectedDate,
        description: _descriptionController.text,
      );

      final managementBloc = context.read<ManagementBloc>();
      managementBloc.add(AddExpense(expense));

      _amountController.clear();
      _descriptionController.clear();
      setState(() {
        _selectedType = ExpenseType.maintenance;
        _selectedDate = DateTime.now();
      });

      Navigator.pop(context); // Close bottom sheet

      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: const Text('Expense added successfully'),
          backgroundColor: Colors.green.shade600,
          behavior: SnackBarBehavior.floating,
        ),
      );
    }
  }

  Future<void> _pickDate(StateSetter setModalState) async {
    final picked = await showDatePicker(
      context: context,
      initialDate: _selectedDate,
      firstDate: DateTime(2020),
      lastDate: DateTime.now().add(const Duration(days: 365)),
    );
    if (picked != null) {
      setModalState(() {
        _selectedDate = picked;
      });
    }
  }

  void _showAddExpenseBottomSheet() {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (context) => StatefulBuilder(
        builder: (context, setModalState) => Container(
          padding: EdgeInsets.only(
            bottom: MediaQuery.of(context).viewInsets.bottom,
          ),
          decoration: const BoxDecoration(
            color: Colors.white,
            borderRadius: BorderRadius.vertical(top: Radius.circular(20)),
          ),
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(24),
            child: Form(
              key: _formKey,
              child: Column(
                mainAxisSize: MainAxisSize.min,
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      const Text(
                        'Add New Expense',
                        style: TextStyle(
                          fontSize: 20,
                          fontWeight: FontWeight.bold,
                        ),
                      ),
                      IconButton(
                        icon: const Icon(CupertinoIcons.xmark),
                        onPressed: () => Navigator.pop(context),
                      ),
                    ],
                  ),
                  const SizedBox(height: 24),
                  DropdownButtonFormField<ExpenseType>(
                    icon: const Icon(CupertinoIcons.chevron_down),
                    initialValue: _selectedType,
                    decoration: const InputDecoration(
                      labelText: 'Expense Category',
                      prefixIcon: Icon(CupertinoIcons.square_grid_2x2),
                    ),
                    items: ExpenseType.values.map((type) {
                      return DropdownMenuItem(
                        value: type,
                        child: Text(
                          type.toString().split('.').last.toUpperCase(),
                        ),
                      );
                    }).toList(),
                    onChanged: (val) {
                      if (val != null) {
                        setModalState(() => _selectedType = val);
                      }
                    },
                  ),
                  const SizedBox(height: 16),
                  TextFormField(
                    controller: _amountController,
                    decoration: const InputDecoration(
                      labelText: 'Amount (د.إ)',
                      prefixIcon: Icon(CupertinoIcons.money_dollar_circle),
                    ),
                    keyboardType:
                        const TextInputType.numberWithOptions(decimal: true),
                    validator: (value) {
                      if (value == null || value.isEmpty) return 'Required';
                      if (double.tryParse(value) == null) {
                        return 'Invalid number';
                      }
                      return null;
                    },
                  ),
                  const SizedBox(height: 16),
                  TextFormField(
                    controller: _descriptionController,
                    decoration: const InputDecoration(
                      labelText: 'Expense name / description',
                      prefixIcon: Icon(CupertinoIcons.doc_text),
                    ),
                    maxLines: 2,
                  ),
                  const SizedBox(height: 16),
                  InkWell(
                    onTap: () => _pickDate(setModalState),
                    child: InputDecorator(
                      decoration: const InputDecoration(
                        labelText: 'Date',
                        prefixIcon: Icon(CupertinoIcons.calendar),
                      ),
                      child: Text(
                        DateFormat('MMM d, yyyy').format(_selectedDate),
                        style: const TextStyle(fontSize: 16),
                      ),
                    ),
                  ),
                  const SizedBox(height: 32),
                  ElevatedButton(
                    onPressed: _submitExpense,
                    style: ElevatedButton.styleFrom(
                      padding: const EdgeInsets.symmetric(vertical: 16),
                    ),
                    child: const Text('Save Expense'),
                  ),
                  const SizedBox(height: 16),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: Colors.white,
      appBar: AppBar(
        title: BlocBuilder<ManagementBloc, ManagementState>(
          builder: (context, state) {
            final rooms =
                state is ManagementLoaded ? state.rooms : <RoomModel>[];
            final room = rooms
                    .where((room) => room.roomId == widget.room.roomId)
                    .firstOrNull ??
                widget.room;
            return Text('Own expenses - ${room.displayName(rooms)}',
                overflow: TextOverflow.ellipsis);
          },
        ),
        elevation: 0,
        backgroundColor: Colors.white,
        actions: [
          IconButton(
            icon: Icon(
              CupertinoIcons.square_pencil,
              size: 30,
            ),
            onPressed: () {
              final state = context.read<ManagementBloc>().state;
              final room = state is ManagementLoaded
                  ? state.rooms
                          .where((room) => room.roomId == widget.room.roomId)
                          .firstOrNull ??
                      widget.room
                  : widget.room;
              _showEditRoomDialog(context, room);
            },
          ),
        ],
      ),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: _showAddExpenseBottomSheet,
        icon: const Icon(CupertinoIcons.plus),
        label: const Text('Add Expense'),
      ),
      body: BlocBuilder<ManagementBloc, ManagementState>(
        builder: (context, state) {
          if (state is ManagementLoaded) {
            // Expenses for this room
            final expenses = state.expenses
                .where((e) => e.roomId == widget.room.roomId)
                .toList()
              ..sort((a, b) => b.date.compareTo(a.date));

            // Income (payments) for tenants in this room
            final tenants = state.tenants
                .where((t) => t.roomId == widget.room.roomId)
                .toList();
            final tenantIds = tenants.map((t) => t.tenantId).toSet();
            final payments = state.payments
                .where((p) => tenantIds.contains(p.tenantId))
                .toList();

            final totalIncome =
                payments.fold<double>(0, (sum, p) => sum + p.amount);
            final totalExpenses =
                expenses.fold<double>(0, (sum, e) => sum + e.amount);

            return CustomScrollView(
              slivers: [
                SliverToBoxAdapter(
                  child: _buildFinancialSummary(totalIncome, totalExpenses),
                ),
                if (expenses.isEmpty)
                  SliverFillRemaining(
                    hasScrollBody: false,
                    child: Center(
                      child: Column(
                        mainAxisAlignment: MainAxisAlignment.center,
                        children: [
                          Icon(
                            CupertinoIcons.doc_text,
                            size: 80,
                            color: Colors.grey.shade300,
                          ),
                          const SizedBox(height: 16),
                          Text(
                            'No expenses recorded',
                            style: TextStyle(
                              fontSize: 18,
                              color: Colors.grey.shade500,
                              fontWeight: FontWeight.w500,
                            ),
                          ),
                        ],
                      ),
                    ),
                  )
                else
                  SliverPadding(
                    padding: const EdgeInsets.symmetric(horizontal: 16),
                    sliver: SliverList(
                      delegate: SliverChildBuilderDelegate(
                        (context, index) => _buildExpenseCard(expenses[index]),
                        childCount: expenses.length,
                      ),
                    ),
                  ),
                const SliverToBoxAdapter(child: SizedBox(height: 100)),
              ],
            );
          }
          return const Center(child: CircularProgressIndicator());
        },
      ),
    );
  }

  Widget _buildFinancialSummary(double income, double expenses) {
    final profit = income - expenses;
    final isPositive = profit >= 0;

    return Container(
      margin: const EdgeInsets.all(16),
      padding: const EdgeInsets.all(24),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(24),
        border: Border.all(color: Colors.grey.shade100),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.02),
            blurRadius: 20,
            offset: const Offset(0, 10),
          ),
        ],
      ),
      child: Column(
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    'Net Balance',
                    style: TextStyle(
                      color: Colors.grey.shade500,
                      fontSize: 14,
                      fontWeight: FontWeight.w500,
                    ),
                  ),
                  const SizedBox(height: 4),
                  Text(
                    'د.إ${profit.toStringAsFixed(0)}',
                    style: TextStyle(
                      fontSize: 32,
                      fontWeight: FontWeight.bold,
                      color: isPositive
                          ? Colors.green.shade600
                          : Colors.red.shade600,
                    ),
                  ),
                ],
              ),
              _buildSimpleDoughnut(income, expenses),
            ],
          ),
          const SizedBox(height: 24),
          Row(
            children: [
              _buildSummaryItem(
                'Income',
                income,
                Colors.blue.shade600,
                CupertinoIcons.arrow_down,
              ),
              const SizedBox(width: 16),
              _buildSummaryItem(
                'Expenses',
                expenses,
                Colors.orange.shade600,
                CupertinoIcons.arrow_up,
              ),
            ],
          ),
        ],
      ),
    );
  }

  Widget _buildSimpleDoughnut(double income, double expenses) {
    final total = income + expenses;

    return Container(
      width: 60,
      height: 60,
      decoration: BoxDecoration(
        shape: BoxShape.circle,
        border: Border.all(color: Colors.grey.shade100, width: 8),
      ),
      child: CircularProgressIndicator(
        value: total > 0 ? income / total : 0.5,
        strokeWidth: 8,
        backgroundColor: Colors.orange.shade400,
        color: Colors.blue.shade400,
      ),
    );
  }

  Widget _buildSummaryItem(
      String label, double amount, Color color, IconData icon) {
    return Expanded(
      child: Container(
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: color.withValues(alpha: 0.05),
          borderRadius: BorderRadius.circular(16),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Icon(icon, size: 14, color: color),
                const SizedBox(width: 4),
                Text(
                  label,
                  style: TextStyle(
                    color: color,
                    fontSize: 12,
                    fontWeight: FontWeight.w600,
                  ),
                ),
              ],
            ),
            const SizedBox(height: 4),
            Text(
              'د.إ${amount.toStringAsFixed(0)}',
              style: TextStyle(
                fontSize: 18,
                fontWeight: FontWeight.bold,
                color: Colors.grey.shade800,
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildExpenseCard(ExpenseModel expense) {
    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(16),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.03),
            blurRadius: 10,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: ClipRRect(
        borderRadius: BorderRadius.circular(16),
        child: Material(
          color: Colors.transparent,
          child: InkWell(
            onLongPress: () => _confirmDelete(context, expense.id!),
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Row(
                children: [
                  Container(
                    padding: const EdgeInsets.all(12),
                    decoration: BoxDecoration(
                      color: _getTypeColor(expense.expenseType)
                          .withValues(alpha: 0.1),
                      shape: BoxShape.circle,
                    ),
                    child: Icon(
                      _getIconForType(expense.expenseType),
                      color: _getTypeColor(expense.expenseType),
                      size: 24,
                    ),
                  ),
                  const SizedBox(width: 16),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          expense.displayName,
                          style: const TextStyle(
                            fontWeight: FontWeight.bold,
                            fontSize: 14,
                            letterSpacing: 0.5,
                            color: Colors.black87,
                          ),
                        ),
                        const SizedBox(height: 4),
                        Text(
                          '${expense.categoryName} · ${DateFormat('MMM d, yyyy').format(expense.date)}',
                          style: TextStyle(
                            color: Colors.grey.shade600,
                            fontSize: 12,
                          ),
                        ),
                      ],
                    ),
                  ),
                  Column(
                    crossAxisAlignment: CrossAxisAlignment.end,
                    children: [
                      Text(
                        'د.إ${expense.amount.toStringAsFixed(0)}',
                        style: const TextStyle(
                          fontWeight: FontWeight.bold,
                          fontSize: 18,
                          color: Colors.redAccent,
                        ),
                      ),
                      IconButton(
                        icon: const Icon(CupertinoIcons.trash,
                            size: 20, color: Colors.grey),
                        onPressed: () => _confirmDelete(context, expense.id!),
                        padding: EdgeInsets.zero,
                        constraints: const BoxConstraints(),
                      ),
                    ],
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }

  Color _getTypeColor(ExpenseType type) {
    switch (type) {
      case ExpenseType.rent:
        return Colors.blue;
      case ExpenseType.sewa:
        return Colors.orange;
      case ExpenseType.maintenance:
        return Colors.purple;
      case ExpenseType.internet:
        return Colors.indigo;
      case ExpenseType.cleaning:
        return Colors.green;
      case ExpenseType.refund:
        return Colors.red;
      case ExpenseType.other:
        return Colors.blueGrey;
    }
  }

  IconData _getIconForType(ExpenseType type) {
    switch (type) {
      case ExpenseType.rent:
        return CupertinoIcons.house;
      case ExpenseType.sewa:
        return CupertinoIcons.lightbulb;
      case ExpenseType.maintenance:
        return CupertinoIcons.hammer;
      case ExpenseType.internet:
        return CupertinoIcons.wifi;
      case ExpenseType.cleaning:
        return CupertinoIcons.paintbrush;
      case ExpenseType.refund:
        return CupertinoIcons.arrow_uturn_left;
      case ExpenseType.other:
        return CupertinoIcons.gear;
    }
  }

  void _confirmDelete(BuildContext context, String expenseId) {
    final managementBloc = context.read<ManagementBloc>();
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      builder: (context) => BlocProvider.value(
        value: managementBloc,
        child: Container(
          padding: const EdgeInsets.all(24),
          decoration: const BoxDecoration(
            color: Colors.white,
            borderRadius: BorderRadius.vertical(top: Radius.circular(20)),
          ),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              Center(
                child: Container(
                  width: 40,
                  height: 4,
                  decoration: BoxDecoration(
                    color: Colors.grey.shade300,
                    borderRadius: BorderRadius.circular(2),
                  ),
                ),
              ),
              const SizedBox(height: 24),
              const Text(
                'Delete Expense',
                style: TextStyle(
                  fontSize: 20,
                  fontWeight: FontWeight.bold,
                  color: Colors.redAccent,
                ),
              ),
              const SizedBox(height: 16),
              const Text(
                'Are you sure you want to remove this expense record? This action cannot be undone.',
                style: TextStyle(
                  fontSize: 16,
                  color: Colors.black54,
                  height: 1.5,
                ),
              ),
              const SizedBox(height: 32),
              ElevatedButton(
                onPressed: () {
                  managementBloc.add(DeleteExpense(expenseId));
                  Navigator.pop(context);
                },
                style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.redAccent,
                  padding: const EdgeInsets.symmetric(vertical: 16),
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(12),
                  ),
                ),
                child: const Text('Delete Expense'),
              ),
              const SizedBox(height: 12),
              OutlinedButton(
                onPressed: () => Navigator.pop(context),
                style: OutlinedButton.styleFrom(
                  padding: const EdgeInsets.symmetric(vertical: 16),
                  side: const BorderSide(color: Colors.grey),
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(12),
                  ),
                ),
                child: const Text(
                  'Cancel',
                  style: TextStyle(color: Colors.grey),
                ),
              ),
              const SizedBox(height: 16),
            ],
          ),
        ),
      ),
    );
  }

  void _showEditRoomDialog(BuildContext context, RoomModel room) {
    final managementBloc = context.read<ManagementBloc>();
    final state = managementBloc.state;
    final rooms = state is ManagementLoaded ? state.rooms : <RoomModel>[];
    String? selectedParentId = room.parentRoomId;
    String? validationError;
    final hasChildren = rooms.any((child) => child.parentRoomId == room.roomId);
    final roomNumberController = TextEditingController(text: room.roomNumber);
    final capacityController = TextEditingController(
      text: room.totalCapacity.toString(),
    );
    final lowerBedsController = TextEditingController(
      text: room.lowerBedsCount.toString(),
    );
    final upperBedsController = TextEditingController(
      text: room.upperBedsCount.toString(),
    );
    final lowerRentController = TextEditingController(
      text: room.lowerBedRent.toString(),
    );
    final upperRentController = TextEditingController(
      text: room.upperBedRent.toString(),
    );

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (sheetContext) => BlocProvider.value(
        value: managementBloc,
        child: StatefulBuilder(
            builder: (context, setModalState) => Container(
                  padding: EdgeInsets.only(
                    bottom: MediaQuery.of(sheetContext).viewInsets.bottom,
                  ),
                  decoration: const BoxDecoration(
                    color: Colors.white,
                    borderRadius:
                        BorderRadius.vertical(top: Radius.circular(20)),
                  ),
                  child: SingleChildScrollView(
                    padding: const EdgeInsets.all(24),
                    child: Column(
                      mainAxisSize: MainAxisSize.min,
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        Center(
                          child: Container(
                            width: 40,
                            height: 4,
                            decoration: BoxDecoration(
                              color: Colors.grey.shade300,
                              borderRadius: BorderRadius.circular(2),
                            ),
                          ),
                        ),
                        const SizedBox(height: 24),
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,
                          children: [
                            const Text(
                              'Edit Room',
                              style: TextStyle(
                                fontSize: 20,
                                fontWeight: FontWeight.bold,
                                color: AppTheme.textColor,
                              ),
                            ),
                            IconButton(
                              icon: const Icon(
                                CupertinoIcons.trash,
                                color: AppTheme.errorColor,
                              ),
                              onPressed: () {
                                Navigator.pop(sheetContext);
                                _showDeleteConfirmation(context, room);
                              },
                            ),
                          ],
                        ),
                        const SizedBox(height: 24),
                        DropdownButtonFormField<String>(
                          icon: const Icon(CupertinoIcons.chevron_down),
                          initialValue: selectedParentId ?? '',
                          isExpanded: true,
                          decoration: const InputDecoration(
                              labelText: 'Inside room (optional)'),
                          items: [
                            const DropdownMenuItem(
                                value: '', child: Text('Main room')),
                            ...rooms
                                .where((parent) =>
                                    !parent.isSubroom &&
                                    parent.roomId != room.roomId &&
                                    parent.buildingId == room.buildingId)
                                .map((parent) => DropdownMenuItem(
                                    value: parent.roomId,
                                    child: Text('Room ${parent.roomNumber}'))),
                          ],
                          onChanged: hasChildren
                              ? null
                              : (value) => setModalState(() =>
                                  selectedParentId =
                                      value == '' ? null : value),
                        ),
                        const SizedBox(height: 16),
                        TextField(
                          controller: roomNumberController,
                          decoration: const InputDecoration(
                            labelText: 'Room Number',
                            prefixIcon:
                                Icon(CupertinoIcons.rectangle_split_3x1),
                          ),
                        ),
                        const SizedBox(height: 16),
                        TextField(
                          controller: capacityController,
                          decoration: const InputDecoration(
                            labelText: 'Total Capacity',
                            prefixIcon: Icon(CupertinoIcons.person_2),
                          ),
                          keyboardType: TextInputType.number,
                        ),
                        const SizedBox(height: 16),
                        Row(
                          children: [
                            Expanded(
                              child: TextField(
                                controller: lowerBedsController,
                                decoration: const InputDecoration(
                                  labelText: 'Lower Beds',
                                  prefixIcon: Icon(CupertinoIcons.bed_double),
                                ),
                                keyboardType: TextInputType.number,
                              ),
                            ),
                            const SizedBox(width: 16),
                            Expanded(
                              child: TextField(
                                controller: upperBedsController,
                                decoration: const InputDecoration(
                                  labelText: 'Upper Beds',
                                  prefixIcon: Icon(CupertinoIcons.bed_double),
                                ),
                                keyboardType: TextInputType.number,
                              ),
                            ),
                          ],
                        ),
                        const SizedBox(height: 16),
                        Row(
                          children: [
                            Expanded(
                              child: TextField(
                                controller: lowerRentController,
                                decoration: const InputDecoration(
                                  labelText: 'Lower Rent',
                                  prefixIcon:
                                      Icon(CupertinoIcons.money_dollar_circle),
                                ),
                                keyboardType: TextInputType.number,
                              ),
                            ),
                            const SizedBox(width: 16),
                            Expanded(
                              child: TextField(
                                controller: upperRentController,
                                decoration: const InputDecoration(
                                  labelText: 'Upper Rent',
                                  prefixIcon:
                                      Icon(CupertinoIcons.money_dollar_circle),
                                ),
                                keyboardType: TextInputType.number,
                              ),
                            ),
                          ],
                        ),
                        const SizedBox(height: 32),
                        if (validationError != null)
                          Text(validationError!,
                              style:
                                  const TextStyle(color: AppTheme.errorColor)),
                        ElevatedButton(
                          onPressed: () {
                            final updated = RoomModel(
                              roomId: room.roomId,
                              buildingId: room.buildingId,
                              parentRoomId: selectedParentId,
                              roomNumber: roomNumberController.text.trim(),
                              totalCapacity:
                                  int.tryParse(capacityController.text) ?? 2,
                              lowerBedsCount:
                                  int.tryParse(lowerBedsController.text) ?? 1,
                              upperBedsCount:
                                  int.tryParse(upperBedsController.text) ?? 1,
                              lowerBedRent:
                                  double.tryParse(lowerRentController.text) ??
                                      0,
                              upperBedRent:
                                  double.tryParse(upperRentController.text) ??
                                      0,
                              utilityCostMonthly: room.utilityCostMonthly,
                              monthlyRent: room.monthlyRent,
                            );
                            try {
                              if (updated.roomNumber.isEmpty) {
                                throw ArgumentError('Enter a room name.');
                              }
                              updated.validateHierarchy(rooms);
                            } on ArgumentError catch (error) {
                              setModalState(() =>
                                  validationError = error.message.toString());
                              return;
                            }
                            managementBloc.add(UpdateRoom(updated));
                            Navigator.pop(sheetContext);
                          },
                          style: ElevatedButton.styleFrom(
                            padding: const EdgeInsets.symmetric(vertical: 16),
                            shape: RoundedRectangleBorder(
                              borderRadius: BorderRadius.circular(12),
                            ),
                          ),
                          child: const Text('Save Changes'),
                        ),
                        const SizedBox(height: 16),
                      ],
                    ),
                  ),
                )),
      ),
    );
  }

  void _showDeleteConfirmation(BuildContext context, RoomModel room) {
    final managementBloc = context.read<ManagementBloc>();
    final state = managementBloc.state;
    if (state is ManagementLoaded &&
        state.rooms.any((child) => child.parentRoomId == room.roomId)) {
      ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
          content: Text('Remove the subrooms before deleting this room.')));
      return;
    }
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      builder: (context) => Container(
        padding: const EdgeInsets.all(24),
        decoration: const BoxDecoration(
          color: Colors.white,
          borderRadius: BorderRadius.vertical(top: Radius.circular(20)),
        ),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Center(
              child: Container(
                width: 40,
                height: 4,
                decoration: BoxDecoration(
                  color: Colors.grey.shade300,
                  borderRadius: BorderRadius.circular(2),
                ),
              ),
            ),
            const SizedBox(height: 24),
            const Text(
              'Delete Room?',
              textAlign: TextAlign.center,
              style: TextStyle(
                fontSize: 20,
                fontWeight: FontWeight.bold,
                color: AppTheme.errorColor,
              ),
            ),
            const SizedBox(height: 16),
            Text(
              'Are you sure you want to delete Room ${room.roomNumber}? This action cannot be undone.',
              textAlign: TextAlign.center,
              style: const TextStyle(
                color: AppTheme.secondaryTextColor,
                fontSize: 16,
              ),
            ),
            const SizedBox(height: 32),
            Row(
              children: [
                Expanded(
                  child: OutlinedButton(
                    onPressed: () => Navigator.pop(context),
                    style: OutlinedButton.styleFrom(
                      padding: const EdgeInsets.symmetric(vertical: 16),
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(12),
                      ),
                    ),
                    child: const Text('Cancel'),
                  ),
                ),
                const SizedBox(width: 16),
                Expanded(
                  child: ElevatedButton(
                    onPressed: () {
                      if (room.roomId != null) {
                        managementBloc.add(DeleteRoom(room.roomId!));
                      }
                      Navigator.pop(context);
                    },
                    style: ElevatedButton.styleFrom(
                      backgroundColor: AppTheme.errorColor,
                      padding: const EdgeInsets.symmetric(vertical: 16),
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(12),
                      ),
                    ),
                    child: const Text(
                      'Delete',
                      style: TextStyle(color: Colors.white),
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 16),
          ],
        ),
      ),
    );
  }
